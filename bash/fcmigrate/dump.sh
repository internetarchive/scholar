WEBCAPTURES_CDX_OUT="webcapturecdx.tsv"

dump_containers() {
  echo "dumping containers to $CONTAINERS_OUT"
  cat << EOF | $PSQL
\copy (
  SELECT
    ci.id AS legacy_ident,
    cr.name,
    to_json(cr.extra_json) AS extra,
    cr.container_type,
    cr.publisher,
    cr.issnl,
    cr.issne,
    cr.issnp,
    cr.wikidata_qid,
    '$SOURCE' AS source
  FROM container_ident ci
  JOIN container_rev cr ON ci.rev_id = cr.id
  WHERE
    ci.is_live = true
    AND
    ci.redirect_id is NULL
    AND
    cr.container_type != 'test'
  ) TO '$CONTAINERS_OUT' WITH (FORMAT CSV, DELIMITER E'\t', HEADER);
EOF
}

