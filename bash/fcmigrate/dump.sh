#!/bin/env bash

# this file creates several large .tsv files from a fatcat database intended for consumption into the new database schema
# make sure you have about a TB to work with if you're running this.

SOURCE="legacy_import"
PSQL="psql -D fatcat_pod"
CONTAINERS_OUT="containers.tsv"
CREATORS_OUT="creators.tsv"
WORKS_OUT="works.tsv"
RELEASES_OUT="releases.tsv"
RELEASES_EXTID_OUT="releaseextids.tsv"
